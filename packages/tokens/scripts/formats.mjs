// Style Dictionary formats for @bumpist/tokens: tokens.css, tailwind.css and tokens.json.
// Every format reads the DTCG tree from to-style-dictionary.mjs (path: theme, category, mode/profile, name).
import { MODES, PROFILES } from "./theme.mjs";

const HEADER = "/* Generated by @bumpist/tokens (Style Dictionary). Do not edit; change src/ and run pnpm build. */\n";

// Tailwind v4 name → --bp-sys-* variable. Only these colors, radii, shadow and spacing exist (UI-001, UI-005).
export const TAILWIND_MAP = [
  ["--color-bg", "color-bg"],
  ["--color-surface", "color-surface"],
  ["--color-surface-raised", "color-surface-raised"],
  ["--color-fg", "color-text"],
  ["--color-fg-muted", "color-text-muted"],
  ["--color-primary", "color-primary"],
  ["--color-on-primary", "color-primary-fg"],
  ["--color-accent", "color-accent"],
  ["--color-on-accent", "color-accent-fg"],
  ["--color-positive", "color-positive"],
  ["--color-notice", "color-notice"],
  ["--color-negative", "color-negative"],
  ["--color-focus-ring", "color-focus-ring"],
  ["--color-input", "color-input"],
  ["--radius-control", "radius-control"],
  ["--radius-container", "radius-container"],
  ["--shadow-overlay", "shadow-overlay"],
  ["--spacing-stack", "space-stack"],
  ["--spacing-section", "space-section"],
];
const TAILWIND_RESETS = ["--color-*", "--radius-*", "--shadow-*", "--inset-shadow-*", "--drop-shadow-*", "--text-shadow-*"];

const value = (t) => t.$value ?? t.value;
const sysVar = (category, name) => `--bp-sys-${category}-${name}`;

// theme → category → (mode | profile | "_") → name → value
function index(dictionary) {
  const out = {};
  for (const t of dictionary.allTokens) {
    const [theme, category, ...rest] = t.path;
    const [group, name] = rest.length === 2 ? rest : ["_", rest[0]];
    ((((out[theme] ??= {})[category] ??= {})[group] ??= {})[name] = value(t));
  }
  return out;
}

function block(selectors, declarations) {
  const body = declarations.map(([k, v]) => `  ${k}: ${v};`).join("\n");
  return `${selectors.join(",\n")} {\n${body}\n}\n`;
}

const vars = (category, group) => Object.entries(group ?? {}).map(([name, v]) => [sysVar(category, name), v]);

export function cssFormat({ dictionary }) {
  const parts = [HEADER];
  for (const [id, t] of Object.entries(index(dictionary))) {
    const root = `:root[data-theme="${id}"]`;
    parts.push(
      `/* ${id}: light is the default when data-mode is missing */\n` +
        block([root, `${root}[data-mode="light"]`], [...vars("color", t.color.light), ...vars("shadow", t.shadow.light)]),
      block([`${root}[data-mode="dark"]`], [...vars("color", t.color.dark), ...vars("shadow", t.shadow.dark)]),
      block([root], vars("radius", t.radius._)),
      `/* ${id}: consumer is the default when data-profile is missing */\n` +
        block([root, `[data-theme="${id}"] [data-profile="consumer"]`, `[data-theme="${id}"][data-profile="consumer"]`], vars("space", t.space.consumer)),
      block([`[data-theme="${id}"] [data-profile="workspace"]`, `[data-theme="${id}"][data-profile="workspace"]`], vars("space", t.space.workspace)),
    );
  }
  return parts.join("\n");
}

export function tailwindFormat({ dictionary }) {
  const known = new Set();
  for (const t of Object.values(index(dictionary)))
    for (const [category, groups] of Object.entries(t))
      for (const g of Object.values(groups)) for (const name of Object.keys(g)) known.add(`${category}-${name}`);
  const missing = TAILWIND_MAP.filter(([, src]) => !known.has(src)).map(([, src]) => src);
  if (missing.length) throw new Error(`tailwind.css maps tokens that do not exist: ${missing.join(", ")}`);
  const resets = TAILWIND_RESETS.map((r) => `  ${r}: initial;`).join("\n");
  const maps = TAILWIND_MAP.map(([tw, src]) => `  ${tw}: var(--bp-sys-${src});`).join("\n");
  return `${HEADER}/* Tailwind v4: only Bumpist tokens exist. Default colors, radii and shadows are reset (UI-001, UI-005). */\n@theme inline {\n${resets}\n\n${maps}\n}\n`;
}

export function jsonFormat({ dictionary }) {
  const out = {};
  for (const [id, t] of Object.entries(index(dictionary))) {
    out[id] = {};
    for (const mode of MODES) {
      out[id][mode] = {};
      for (const profile of PROFILES)
        out[id][mode][profile] = {
          color: t.color[mode],
          radius: t.radius._,
          shadow: t.shadow[mode],
          space: t.space[profile],
        };
    }
  }
  return `${JSON.stringify(out, null, 2)}\n`;
}

export function registerFormats(StyleDictionary) {
  StyleDictionary.registerFormat({ name: "bumpist/css", format: cssFormat });
  StyleDictionary.registerFormat({ name: "bumpist/tailwind", format: tailwindFormat });
  StyleDictionary.registerFormat({ name: "bumpist/json", format: jsonFormat });
}
